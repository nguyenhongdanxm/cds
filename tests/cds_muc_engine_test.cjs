'use strict';
const assert=require('node:assert/strict'),E=require('../assets/cds-muc-engine.js');
const rows=[{id:'a',name:'Nguyễn An',gender:'Nam'},{id:'b',name:'Nguyễn An',gender:'Nữ'},{id:'c',name:'Lê Chi'}];
const rng=(...values)=>({getRandomValues(out){out[0]=values.shift()??0;return out;}});
assert.throws(()=>E.randomIndex(0,rng(0)));
assert.throws(()=>E.randomIndex(1.5,rng(0)));
assert.equal(E.randomIndex(3,rng(0xffffffff,5)),2,'Rejects modulo bias at uint32 tail');
assert.equal(E.randomIndex(1,rng(0xffffffff)),0);
const game=new E.Game([...rows,rows[0],null,{id:'x',name:''}]);
assert.equal(game.students.length,3);assert.equal(game.students[1].gender,'Nữ');
assert.equal(game.begin(rng(1)).winner.id,'b','Same names retain distinct student IDs');
assert.equal(game.begin(rng(0)),null,'Double click does not start a second round');
game.cancel();assert.equal(game.history.length,0);assert.equal(game.called.size,0,'Cancellation never marks a pupil called');
assert.equal(game.finish(),null,'Cancelled round cannot finish');
game.selected.delete('a');assert.equal(game.available().length,2);
assert.equal(game.begin(rng(0)).winner.id,'b');assert.equal(game.finish().id,'b');assert.equal(game.finish(),null,'Finish is idempotent');
assert.deepEqual(game.available().map(s=>s.id),['c']);game.begin(rng(0));game.finish();assert.equal(game.begin(rng(0)),null,'Exhausted selection is blocked');
game.noRepeat=false;assert.equal(game.available().length,2);game.begin(rng(0));game.finish();assert.equal(game.history.length,3);
const saved=game.snapshot(),restored=new E.Game(rows,JSON.parse(JSON.stringify(saved)));assert.deepEqual(restored.snapshot(),saved);
const cleaned=new E.Game(rows,{selected:['a','deleted'],called:['b','deleted'],history:[{id:'b',time:100},{id:'deleted',time:100},{id:'c',time:'bad'}]});assert.deepEqual([...cleaned.selected],['a']);assert.deepEqual([...cleaned.called],['b']);assert.equal(cleaned.history.length,1);
assert.equal(new E.Game(rows,{selected:[]}).available().length,0,'An intentionally empty selection stays empty');
assert.equal(new E.Game(rows,null).available().length,3);
assert.equal(new E.Game([]).begin(rng(0)),null);
for(const [p,phase] of [[0,'sneak'],[.34,'wake'],[.44,'chase'],[.89,'catch'],[1,'catch']])assert.equal(E.phase(p),phase);
for(let i=0;i<rows.length;i++)assert.equal(new E.Game(rows).begin(rng(i)).winner.id,rows[i].id,'Every eligible ID can be selected');
console.log('PASS Mực engine: unbiased random, duplicate names, selection, cancel, double-start/finish, no-repeat, exhaustion, restore and phases');
